export function slugToCatKeyPrefix(slug) {
  return `cat_${slug.replace(/-/g, "_")}`;
}

export function categoryTitleKey(slug) {
  return `${slugToCatKeyPrefix(slug)}_title`;
}

export function categoryDescKey(slug) {
  return `${slugToCatKeyPrefix(slug)}_desc`;
}

/**
 * @param {AppLang|string} language
 * @param {string} key
 */
export function t(language, key) {
  const lang = language === "ku" ? "ku" : "en";
  const val = translations[lang]?.[key];
  if (val !== undefined && val !== null && String(val).trim() !== "") {
    return val;
  }
  console.warn(`[i18n] Missing translation for key "${key}" (locale: ${lang})`);
  if (lang === "ku") {
    return `[${key}]`;
  }
  const enVal = translations.en?.[key];
  if (enVal !== undefined && enVal !== null && String(enVal).trim() !== "") {
    return enVal;
  }
  return `[${key}]`;
}
