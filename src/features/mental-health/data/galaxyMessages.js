/**
 * Small, fast, seedable pseudo-random number generator (mulberry32).
 * Deterministic: the same seed always produces the same sequence.
 */
function createSeededRandom(seed) {
  let state = seed >>> 0;
  return function random() {
    state = (state + 0x6d2b79f5) >>> 0;
    let t = state;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** Fisher-Yates shuffle driven by a seeded random source, for reproducible ordering. */
function seededShuffle(items, random) {
  const result = items.slice();
  for (let i = result.length - 1; i > 0; i -= 1) {
    const j = Math.floor(random() * (i + 1));
    const temp = result[i];
    result[i] = result[j];
    result[j] = temp;
  }
  return result;
}

/** Builds a numeric seed from the current date, formatted as YYYYMMDD. */
function getSeedFromToday() {
  const now = new Date();
  const year = now.getFullYear();
  const month = String(now.getMonth() + 1).padStart(2, "0");
  const day = String(now.getDate()).padStart(2, "0");
  return Number(`${year}${month}${day}`);
}

const GALAXY_X_MIN = 6;
const GALAXY_X_MAX = 94;
const GALAXY_Y_MIN = 8;
const GALAXY_Y_MAX = 88;
const GALAXY_SIZE_MIN = 4;
const GALAXY_SIZE_MAX = 14;
const MAX_PLACEMENT_ATTEMPTS = 40;

/**
 * Deterministic daily subset of stars with no near-duplicate placement by spacing.
 *
 * Every message in GALAXY_MESSAGES is unique in content, so "no near-duplicates"
 * is enforced spatially: stars are placed with a minimum distance from one
 * another so the same day never renders two stars crowded on top of each other.
 *
 * @param {number} count - How many stars to pick for the day (default 48).
 * @param {number|string|null} daySeed - Optional explicit seed. When null, a
 *   seed is derived from today's date (YYYYMMDD), so the result is stable for
 *   the whole day and changes automatically the next day.
 * @returns {Array<{id:string,en:string,ku:string,x:number,y:number,size:number,twinkle:{delay:number,duration:number}}>}
 */
export function pickDailyGalaxyStars(count = 48, daySeed = null) {
  const seed = daySeed == null ? getSeedFromToday() : Number(daySeed);
  const random = createSeededRandom(Number.isFinite(seed) ? seed : getSeedFromToday());

  const shuffled = seededShuffle(GALAXY_MESSAGES, random);
  const starCount = Math.max(0, Math.min(count, shuffled.length));
  const chosenMessages = shuffled.slice(0, starCount);

  const usableArea = (GALAXY_X_MAX - GALAXY_X_MIN) * (GALAXY_Y_MAX - GALAXY_Y_MIN);
  const idealSpacing = starCount > 0 ? Math.sqrt(usableArea / starCount) : 0;
  const minDistance = Math.min(14, Math.max(4, idealSpacing * 0.62));

  const placedPositions = [];

  return chosenMessages.map((message) => {
    let x = GALAXY_X_MIN + random() * (GALAXY_X_MAX - GALAXY_X_MIN);
    let y = GALAXY_Y_MIN + random() * (GALAXY_Y_MAX - GALAXY_Y_MIN);
    let attempts = 0;

    while (attempts < MAX_PLACEMENT_ATTEMPTS) {
      const tooClose = placedPositions.some((point) => {
        const dx = point.x - x;
        const dy = point.y - y;
        return Math.sqrt(dx * dx + dy * dy) < minDistance;
      });
      if (!tooClose) break;
      x = GALAXY_X_MIN + random() * (GALAXY_X_MAX - GALAXY_X_MIN);
      y = GALAXY_Y_MIN + random() * (GALAXY_Y_MAX - GALAXY_Y_MIN);
      attempts += 1;
    }

    placedPositions.push({ x, y });

    const size = GALAXY_SIZE_MIN + random() * (GALAXY_SIZE_MAX - GALAXY_SIZE_MIN);
    const twinkle = {
      delay: Number((random() * 5).toFixed(2)),
      duration: Number((2.5 + random() * 3.5).toFixed(2)),
    };

    return {
      ...message,
      x: Number(x.toFixed(2)),
      y: Number(y.toFixed(2)),
      size: Number(size.toFixed(2)),
      twinkle,
    };
  });
}
