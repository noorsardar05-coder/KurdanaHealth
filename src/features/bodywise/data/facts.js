/** Stable fact for a calendar day (same for all users that day). */
export function factOfTheDay(date = new Date()) {
  const start = new Date(date.getFullYear(), 0, 0);
  const day = Math.floor((date - start) / 86400000);
  return BODY_FACTS[day % BODY_FACTS.length];
}

export function randomFact(excludeIndex = -1) {
  let i = Math.floor(Math.random() * BODY_FACTS.length);
  if (BODY_FACTS.length > 1 && i === excludeIndex) {
    i = (i + 1) % BODY_FACTS.length;
  }
  return { fact: BODY_FACTS[i], index: i };
}

export function shuffle(arr) {
  const a = [...arr];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}
