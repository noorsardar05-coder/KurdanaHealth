import { bi } from "../../utils/locale.js";

/**
 * Compact bilingual product factory for the Beauty Encyclopedia.
 * Ingredient names stay scientific (shared). Brand names stay Latin.
 */
export function defineProduct({
  id,
  brand,
  nameEn,
  nameKu,
  category,
  tags = [],
  collections = [],
  descriptionEn,
  descriptionKu,
  forWhomEn,
  forWhomKu,
  ingredients = [],
  benefitsEn = [],
  benefitsKu = [],
  howToUseEn,
  howToUseKu,
  skinTypes = [],
  hairTypes = [],
  concernsEn = [],
  concernsKu = [],
  timeOfDayEn = "Morning & Night",
  timeOfDayKu = "بەیانی و شەو",
  textureEn = "",
  textureKu = "",
  size = "",
  originEn = "",
  originKu = "",
  avoidEn = "",
  avoidKu = "",
  pairsWith = [],
  similarAlternatives = [],
  dermNotesEn = "",
  dermNotesKu = "",
}) {
  return {
    id,
    brand,
    name: bi(nameEn, nameKu),
    category,
    tags,
    collections,
    description: bi(descriptionEn, descriptionKu),
    forWhom: bi(forWhomEn, forWhomKu),
    ingredients,
    benefits: bi(benefitsEn, benefitsKu),
    howToUse: bi(howToUseEn, howToUseKu),
    skinTypes,
    hairTypes,
    concerns: bi(concernsEn, concernsKu),
    timeOfDay: bi(timeOfDayEn, timeOfDayKu),
    texture: bi(textureEn, textureKu),
    size,
    origin: bi(originEn, originKu),
    avoid: bi(avoidEn, avoidKu),
    pairsWith,
    similarAlternatives,
    dermNotes: dermNotesEn || dermNotesKu ? bi(dermNotesEn, dermNotesKu) : null,
  };
}
